#!/usr/bin/env python3
"""Write ../netlist-revB.md, ../bom-revB.csv and reports/test-pads.md from the same sources as the KiCad project, so the docs can't drift.

    python3 -I gen_docs.py      (run_pipeline.sh calls it last)
"""
import os
import shutil
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import wavehat_design as D  # noqa: E402
import gen_schematic as G  # noqa: E402

nets, nc = defaultdict(list), []
for ref, p in sorted(D.P.items()):
    names = G.pin_names(p["lib_id"]) if p["pins"] else {}
    for num, net in sorted(p["pins"].items(), key=lambda kv: (len(kv[0]), kv[0])):
        label = "%s.%s" % (ref, num) + (" (%s)" % names[num] if names.get(num) and names[num] != num else "")
        (nets[net] if net else nc).append(label)

order = sorted(nets, key=lambda n: (n != "GND", n not in D.POWER_NETS, n))
lines = ["# WaveHat rev B: netlist", "",
         "Generated by `kicad-revB/gen_docs.py` from `kicad-revB/wavehat_design.py`, the same file the schematic and PCB are built from. "
         "Don't edit by hand.", "",
         "Pin numbers: LSM6DSO from ST AN5192; TPS560430 from TI SLVSE22B; XIAO pads 1-14 from Seeed's OPL KiCad library "
         "(identical on the C3, C6 and S3). CAN pins and the 0x6B address follow the Takuma project's XIAO node.", "",
         "| Net | Class | Connects |", "|---|---|---|"]
for n in order:
    cls = "Power" if n in D.POWER_NETS else ("Supply 0.3 mm" if n in D.SUPPLY_NETS else ("pour" if n == "GND" else "signal"))
    lines.append("| `%s` | %s | %s |" % (n, cls, ", ".join(nets[n])))
lines += ["", "**No connect:** " + ", ".join(nc), "",
          "**Mechanical:** connector MP tabs unconnected; H1/H2 on GND; FID1-3 no net.", "",
          "**Bottom side, bare copper (not assembled):** JP1-JP10 solder jumpers (JP8-JP10 isolate the CAN transceiver: cut all three for a build with no CAN), TP1-TP30 test pads (`kicad-revB/reports/test-pads.md`), J4 NMEA 2000 / 5-30 V pads. **DNP:** J5 GNSS port, J7 battery holes (U4 pads 15-18 are the carrier pads under the XIAO's own battery pads).", ""]
open(os.path.join(HERE, "..", "netlist-revB.md"), "w").write("\n".join(lines))

bom = os.path.join(HERE, "fab", "wavehat-bom.csv")
if os.path.exists(bom):
    shutil.copy(bom, os.path.join(HERE, "..", "bom-revB.csv"))

# test pads: the bottom-side probe points, numbered as the silkscreen shows them
PARTNER = {   # a component-side pad on the same net, so a bottom pad to it proves the net's vias
    "SDA": "U4.5 (XIAO D4) or J2.3", "SCL": "U4.6 (XIAO D5) or J2.4", "SDA_PU": "R1.2", "SCL_PU": "R2.2", "SA0": "U1.1 (under the IMU; JP3.2 instead)",
    "3V3": "U4.12 (XIAO 3V3)", "IMU_INT1": "U1.4 (under the IMU; JP4.1 instead)", "IMU_INT2": "U1.9 (under the IMU; JP5.1 instead)",
    "GND": "U4.13 (XIAO GND) or H1", "UART_TX": "U4.7 (XIAO D6), J5.2 or J6.6", "UART_RX": "U4.8 (XIAO D7), J5.3 or J6.7",
    "CANH": "J3.3 or U3.7", "CANL": "J3.2 or U3.6", "CAN_TX": "U4.2 (XIAO D1), J6.9 or U3.1 (through JP10)", "CAN_RX": "U4.1 (XIAO D0), J6.8 or U3.4 (through JP9)",
    "TERM": "R5.2", "5V_CAN": "J3.4 or D3.2", "VIN_RAW": "F1.1", "VIN": "C4.1 or TVS1.1", "5V_BUCK": "C5.1 or D2.2",
    "XIAO_5V": "U4.14 (XIAO 5V) or D2.1", "CB": "C6.1 or U2.1", "SD_CS": "JP7.2 (bottom) / R9.2", "SD_SCK": "U4.9 (XIAO D8)",
    "SD_MISO": "U4.10 (XIAO D9)", "SD_MOSI": "U4.11 (XIAO D10)", "LED_R": "U4.3 (XIAO D2)", "LED_B": "U4.4 (XIAO D3)",
}
tl = ["# WaveHat rev B test pads", "",
      "Generated by `gen_docs.py` from `wavehat_design.py`. All on the **bottom** side, 1.0 mm round (TP1, TP2 1.5 mm), "
      "numbered on the silkscreen as TPn. Positions are mm from the board's lower-left corner **seen from the component "
      "side** (the Gerber and pick-and-place origin); the bottom-view x, as you look at the pads, is %.0f minus that." % D.BOARD_W, "",
      "Each pad is on a net that crosses between layers, so a reading from the pad to its component-side partner proves "
      "that net's vias (twinned in rev B). TP22, TP23 and TP8 also let the power stage run from a bench supply before a XIAO "
      "is fitted: feed 12 V between J4 pad 2 and pad 3, expect about 5.1 V on TP22, 4.7 V on TP23, and 3V3 on TP8 only once a XIAO is on.", "",
      "| Pad | Net | x | y | Partner on the component side | Purpose |", "|---|---|---|---|---|---|"]
PURPOSE = {"SDA": "I2C data (IMU, J2, J5)", "SCL": "I2C clock", "SDA_PU": "SDA pull-up side of JP1", "SCL_PU": "SCL pull-up side of JP2",
           "SA0": "IMU address pin (JP3)", "3V3": "XIAO 3.3 V rail", "IMU_INT1": "IMU INT1 (JP4)", "IMU_INT2": "IMU INT2 (JP5)",
           "GND": "ground reference", "UART_TX": "GNSS UART, XIAO D6 out", "UART_RX": "GNSS UART, XIAO D7 in", "CANH": "CAN high",
           "CANL": "CAN low", "CAN_TX": "transceiver TXD from XIAO D1", "CAN_RX": "transceiver RXD to XIAO D0", "TERM": "120 R side of JP6",
           "5V_CAN": "5 V out to J3", "VIN_RAW": "input before the fuse", "VIN": "input after fuse and reverse diode", "5V_BUCK": "buck output, before D2",
           "XIAO_5V": "XIAO 5V pin rail", "CB": "buck bootstrap", "SD_CS": "SD NAND chip select", "SD_SCK": "SD NAND clock",
           "SD_MISO": "SD NAND data out", "SD_MOSI": "SD NAND data in", "LED_R": "XIAO D2 / INT1 option", "LED_B": "XIAO D3 / SD CS through JP7"}
tps = sorted(((int(r[2:]), r, p) for r, p in D.P.items() if r.startswith("TP")))
for n, ref, p in tps:
    net = p["pins"]["1"]
    x, y = p["pcb"][0], p["pcb"][1]
    note = PURPOSE.get(net, "")
    if net == "3V3" and y > 50:
        note = "3V3 on the SD NAND island (rev A board 2's open via)"
    tl.append("| %s | %s | %.2f | %.2f | %s | %s |" % (ref, net, x, D.BOARD_L - y, PARTNER.get(net, ""), note))
tl += ["", "Rows, bottom view with the bow away from you: TP3-TP8 and TP9-TP13 behind the sensor zone, TP14-TP19 between the CAN "
       "parts and the J4 pads, TP20-TP25 under the power stage, TP26-TP30 behind the SD NAND under the XIAO. TP1 and TP2 are "
       "the rev A pads by the INT jumpers.", ""]
os.makedirs(os.path.join(HERE, "reports"), exist_ok=True)
open(os.path.join(HERE, "reports", "test-pads.md"), "w").write("\n".join(tl))
print("wrote netlist-revB.md (%d nets), bom-revB.csv and reports/test-pads.md (%d pads)" % (len(nets), len(tps)))
