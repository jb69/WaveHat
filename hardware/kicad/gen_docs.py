#!/usr/bin/env python3
"""Write ../netlist.md and ../bom.csv from the same sources as the KiCad project, so the docs can't drift.

    python3 -I gen_docs.py      (run_pipeline.sh calls it last)
"""
import os
import shutil
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import wavehat_design as D  # noqa: E402
import gen_schematic as G  # noqa: E402

nets, nc = defaultdict(list), []
for ref, p in sorted(D.P.items()):
    names = G.pin_names(p["lib_id"]) if p["pins"] else {}
    for num, net in sorted(p["pins"].items(), key=lambda kv: (len(kv[0]), kv[0])):
        label = "%s.%s" % (ref, num) + (" (%s)" % names[num] if names.get(num) and names[num] != num else "")
        (nets[net] if net else nc).append(label)

order = sorted(nets, key=lambda n: (n != "GND", n not in D.POWER_NETS, n))
lines = ["# WaveHat rev A: netlist", "",
         "Generated by `kicad/gen_docs.py` from `kicad/wavehat_design.py`, the same file the schematic and PCB are built from. "
         "Don't edit by hand.", "",
         "Pin numbers: LSM6DSO from ST AN5192; TPS560430 from TI SLVSE22B; XIAO pads 1-14 from Seeed's OPL KiCad library "
         "(identical on the C3, C6 and S3). CAN pins and the 0x6B address follow the Takuma project's XIAO node.", "",
         "| Net | Class | Connects |", "|---|---|---|"]
for n in order:
    cls = "Power" if n in D.POWER_NETS else ("pour" if n == "GND" else "signal")
    lines.append("| `%s` | %s | %s |" % (n, cls, ", ".join(nets[n])))
lines += ["", "**No connect:** " + ", ".join(nc), "",
          "**Mechanical:** connector MP tabs unconnected; H1/H2 on GND; FID1-3 no net.", "",
          "**Bottom side, bare copper (not assembled):** JP1-JP6 solder jumpers, TP1-TP3 test pads, J4 NMEA 2000 / 12 V pads.", ""]
open(os.path.join(HERE, "..", "netlist.md"), "w").write("\n".join(lines))

bom = os.path.join(HERE, "fab", "wavehat-bom.csv")
if os.path.exists(bom):
    shutil.copy(bom, os.path.join(HERE, "..", "bom.csv"))
print("wrote netlist.md (%d nets) and bom.csv" % len(nets))
